"""Bundle three paired cache records for the offline presentation. No model calls."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CASES = [
    ("2025-03-17", "00_to_01", "Familiarity, not frequency", "01", "A decline in days of experience does not necessarily mean losing familiarity.",
     "Compare Tom Werner’s 6 → 1 days of client experience. Both values mean ‘known’ under this policy. The cached assessment gives the decline more weight. Also distinguish priority-group counts from availability across all changed assignments."),
    ("2025-03-18", "03_to_10", "Coverage comes first", "02", "An improvement elsewhere cannot override a high-priority coverage loss.",
     "Max Bauer appears only in the removed assignments. Ben Bauer remains assigned with a different employee. The rule rejects the change; the cached model also describes a critical coverage loss but uses the milder ‘eher ablehnen’ label."),
    ("2025-03-19", "06_to_20", "Several risks, one decision", "03", "Different explanation mechanisms can reach the same recommendation.",
     "Leon Richter moves from a familiar client and school to unfamiliar ones, with a 51-minute commute. Both approaches lean toward rejection. Raising the commute threshold to 51 removes that flag, but the familiarity rule still applies."),
]


def main():
    examples = []
    for date, edge, title, number, subtitle, note in CASES:
        diff_path = ROOT / "cache_experiments/cache_diffs" / date / f"{edge}.json"
        eval_path = ROOT / "cache_experiments/cache_evaluations/full__Qwen3_6-27B" / date / f"{edge}.json"
        diff = json.loads(diff_path.read_text(encoding="utf-8"))
        evaluation = json.loads(eval_path.read_text(encoding="utf-8"))
        assert evaluation["diff_reference"] == diff_path.relative_to(ROOT).as_posix()
        assert evaluation["parent_index"] == diff["parent_index"]
        assert evaluation["recommendation_index"] == diff["child_index"]
        examples.append(dict(
            id=f"{date}/{edge}", title=title, number=number, subtitle=subtitle, note=note,
            date=date, edge=edge, model=evaluation["model"], mode=evaluation["evaluation_mode"],
            diff=diff["diff"], assessment=evaluation["assessment"],
            sources=[dict(path=p.relative_to(ROOT).as_posix(), sha256=hashlib.sha256(p.read_bytes()).hexdigest())
                     for p in (diff_path, eval_path)],
        ))
    target = Path(__file__).with_name("examples.js")
    target.write_text("// Generated by build_examples.py; original cached evidence and output.\n"
                      "const EXAMPLES = " + json.dumps(examples, ensure_ascii=False, indent=2)
                      + ";\nif (typeof module !== 'undefined') module.exports = EXAMPLES;\n", encoding="utf-8")
    print(f"Bundled {len(examples)} paired examples into {target.name}")


if __name__ == "__main__":
    main()
